/** `hard` and `soft` are the two tempers a route opens on; the eighteen-year-old chapter answers to them. */
const stance = (prompt: string, hardLine: string, softLine: string, hard: Beat[], soft: Beat[]): Beat => choice('stance', prompt, [
 opt('hard', '刚', hardLine, '腔势 +5 · 心气 +4', hard, { effect: { face: 5, spirit: 4 } }),
 opt('soft', '稳', softLine, '本事 +4 · 心气 +2', soft, { effect: { skill: 4, spirit: 2 } }),
]);
/** `stay` wins the guide's trust; `prepare` banks a reserve for the chapter that follows. */
const parting = (prompt: string, friend: string, stayLine: string, prepareLine: string, stay: Beat[], prepare: Beat[]): Beat =>
 choice('parting', prompt, [
  opt('stay', '情', stayLine, `${friend}信任 +3`, stay, { mood: 'tender' }),
  opt('prepare', '谋', prepareLine, '多一张底牌', prepare),
 ]);

